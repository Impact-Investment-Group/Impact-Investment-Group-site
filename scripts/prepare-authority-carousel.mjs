import assert from "node:assert/strict";
import { mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const countryCounts = { England: 317, Scotland: 32, Wales: 22, "Northern Ireland": 11 };
// Preserve the established four-country opening sequence before the alphabetical remainder.
const openingCodes = [
  "E08000025",
  "S12000036",
  "W06000011",
  "N09000003",
  "E08000003",
  "E06000052",
  "S12000049",
  "W06000022",
  "N09000001",
  "E10000017",
  "E06000015",
  "S12000047",
  "W06000005",
  "N09000011",
  "E06000058",
  "E06000023",
  "S12000033",
  "E06000016",
];

export function validateAuthorityCatalogue(catalogue, publicRoot) {
  const authorities = catalogue?.authorities;
  assert(
    Array.isArray(authorities) && authorities.length === 382,
    "The authority carousel must contain all 382 entries",
  );
  const codes = new Set();
  const counts = Object.fromEntries(Object.keys(countryCounts).map((country) => [country, 0]));
  for (const row of authorities) {
    assert(row && typeof row === "object", "Every authority must be an object");
    assert(
      typeof row.gss_code === "string" &&
        /^[ENSW]\d{8}$/.test(row.gss_code) &&
        !codes.has(row.gss_code),
      `Invalid or duplicate GSS code: ${row.gss_code}`,
    );
    codes.add(row.gss_code);
    assert(
      typeof row.name === "string" && row.name.trim() && typeof row.area_name === "string",
      `Missing authority name: ${row.gss_code}`,
    );
    assert(Object.hasOwn(countryCounts, row.country), `Unknown country: ${row.gss_code}`);
    counts[row.country] += 1;
    const website = new URL(row.website);
    assert(
      ["http:", "https:"].includes(website.protocol) && website.hostname,
      `Invalid official website: ${row.gss_code}`,
    );
    assert.equal(
      row.logo,
      `/images/logos/councils/uk/${row.gss_code}.webp`,
      `Logo must use its canonical local path: ${row.gss_code}`,
    );
    const image = join(publicRoot, row.logo.slice(1));
    assert(
      statSync(image).isFile() && statSync(image).size > 0,
      `Missing or empty authority logo: ${row.gss_code}`,
    );
  }
  assert.deepEqual(
    counts,
    countryCounts,
    "Authority counts must match the reviewed four-country roster",
  );
  return authorities;
}

export function renderAuthorityCarousel(authorities) {
  const byCode = new Map(authorities.map((row) => [row.gss_code, row]));
  const opening = openingCodes.map((code) => {
    const row = byCode.get(code);
    assert(row, `The established carousel opening authority is missing: ${code}`);
    return row;
  });
  const openingSet = new Set(openingCodes);
  const remaining = authorities
    .filter((row) => !openingSet.has(row.gss_code))
    .sort((a, b) => a.name.localeCompare(b.name, "en-GB") || a.gss_code.localeCompare(b.gss_code));
  const ordered = [...opening, ...remaining];
  assert(
    ordered.length === 382 && new Set(ordered.map((row) => row.gss_code)).size === 382,
    "The carousel must preserve all 382 unique authorities",
  );
  const pairs = ordered
    .map((row) => `  [${JSON.stringify(row.gss_code)}, ${JSON.stringify(row.name)}],`)
    .join("\n");
  return (
    `// Generated by scripts/prepare-authority-carousel.mjs; edit the canonical public catalogue.\n` +
    `// Only identifiers and names enter the browser bundle; source metadata stays in public/data/.\n` +
    `import type { LogoCredit } from "@/content/trust";\n\n` +
    `const authorities = [\n${pairs}\n] as const;\n\n` +
    `export const authorityCarousel: LogoCredit[] = authorities.map(([gssCode, name]) => ({\n` +
    `  name,\n` +
    "  logo: `/images/logos/councils/uk/${gssCode}.webp`,\n" +
    `}));\n`
  );
}

export function prepareAuthorityCarousel(root = projectRoot) {
  const publicRoot = join(root, "public");
  const catalogue = JSON.parse(
    readFileSync(join(publicRoot, "data/uk-local-authorities.json"), "utf8"),
  );
  const authorities = validateAuthorityCatalogue(catalogue, publicRoot);
  const target = join(root, "src/content/authority-carousel.ts");
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, renderAuthorityCarousel(authorities));
  console.log(
    `authority-carousel: prepared ${authorities.length} real-logo entries across four countries`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  prepareAuthorityCarousel();
